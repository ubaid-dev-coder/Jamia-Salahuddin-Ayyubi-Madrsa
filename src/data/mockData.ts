// Helper to generate monthly salary records for any month
export const generateDefaultSalaryRecords = (
  staffList: StaffMember[],
  monthStr: string = '2026-05',
  monthUrdu: string = 'مئی ۲۰۲۶',
  yearNum: number = 2026
): MonthlySalaryRecord[] => {
  return staffList.map((staff, idx) => {
    // Generate realistic initial register state for display
    const baseSalary = staff.monthlySalary;
    const attendanceDays = 30;
    const leaveDays = idx % 5 === 0 ? 1 : 0;
    const lateDays = idx % 7 === 0 ? 1 : 0;
    const advance = idx === 3 ? 3000 : idx === 8 ? 2000 : 0;
    const allowances = idx === 0 ? 5000 : idx === 1 ? 2000 : 0;
    const deductions = leaveDays > 1 ? 500 : 0;

    // Net Payable = baseSalary + allowances - deductions - advance
    const netPayable = Math.max(0, baseSalary + allowances - deductions - advance);
    // Initial paid amount (most fully paid, some partial, some pending)
    let paidAmount = netPayable;
    let paymentStatus: 'paid' | 'partial' | 'pending' = 'paid';

    if (idx === 4 || idx === 10) {
      paidAmount = Math.round(netPayable * 0.5);
      paymentStatus = 'partial';
    } else if (idx === 18 || idx === 24) {
      paidAmount = 0;
      paymentStatus = 'pending';
    }

    const remainingAmount = Math.max(0, netPayable - paidAmount);

    return {
      id: `SAL-${monthStr}-${staff.id}`,
      staffId: staff.id,
      month: monthStr,
      monthUrdu,
      year: yearNum,
      baseSalary,
      attendanceDays,
      leaveDays,
      lateDays,
      advance,
      allowances,
      deductions,
      netPayable,
      paidAmount,
      remainingAmount,
      paymentStatus,
      paymentDate: paidAmount > 0 ? `${monthStr}-05` : undefined,
      paymentMethod: 'cash',
      updatedAt: new Date().toISOString(),
    };
  });
};
